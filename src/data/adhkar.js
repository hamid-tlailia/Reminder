/** إزالة التشكيل لمن يفضّل القراءة بغير تشكيل */
export function stripTashkeel(text) {
 return String(text)
  .replace(/[\u064B-\u0652\u0670\u06D6-\u06ED]/g, '')
  .replace(/\u0640/g, '');
}
